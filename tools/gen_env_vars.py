#!/usr/bin/env python3
"""Generate docs/reference/environment.md — every environment variable the code reads, from the code.

    python3 tools/gen_env_vars.py            # rewrite docs/reference/environment.md
    python3 tools/gen_env_vars.py --write    # the same
    python3 tools/gen_env_vars.py --check    # exit 1 if the page is stale or a variable is undescribed (CI)

The names are found by scanning the source for reads: `os.environ.get("X")`, `os.environ["X"]`,
`os.getenv("X")` and `env.get("X")` in Python under webapp/, services/, tools/ and scripts/;
`process.env.X` and `import.meta.env.X` in frontend/src, frontend/astro.config.* and docs-site/
(node_modules, dist, the pinned sibling copies and tests excluded). An assignment is not a read.
The one thing written by hand is the sidecar docs/reference/environment.descriptions.json: one
sentence per variable saying what it changes. A variable the code reads with no description, or a
description for a variable nothing reads, fails the generation — so the page can never omit or
invent one. Names only: the page never carries a value. Stdlib only; no database needed.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reference" / "environment.md"
DESCRIPTIONS = ROOT / "docs" / "reference" / "environment.descriptions.json"
HEADER = ("<!-- generated by tools/gen_env_vars.py from the code that reads each variable and "
          "docs/reference/environment.descriptions.json — do not edit; run the generator -->")

PY, JS = (".py",), (".mjs", ".js", ".ts", ".tsx", ".astro")
# (directory, suffixes, file-name glob or None for every file below it)
SCAN = [("webapp", PY, None), ("services", PY, None), ("tools", PY, None), ("scripts", PY, None),
        ("frontend/src", JS, None), ("frontend", JS, "astro.config.*"), ("docs-site", JS, None)]
SKIP_DIRS = {"node_modules", "dist", ".sources", ".astro", "__pycache__", "tests", "test", "e2e",
             "e2e-live", "e2e-visual", "qa-shots", ".dataset-cache"}
SKIP_FILE = re.compile(r"^(test_.*\.py|.*\.(test|spec)\.[a-z]+|playwright(\..*)?\.config\.[a-z]+)$")
# Set by the CI runner itself, never by a person: not documented here.
IGNORED = {
    "CI": "set by every CI runner; git-dates.mjs refuses a shallow checkout under it",
    "GITHUB_OUTPUT": "the GitHub Actions step-output file",
    "GITHUB_REPOSITORY": "owner/name of the repository a workflow runs in",
}
# Reads the patterns cannot see (the name reaches the environment through a helper). Each entry is
# checked: the file must still contain the name as a string, or the generation fails.
INDIRECT = {"DOCS_PAGE_ACTIONS": ["docs-site/plugins/features.mjs"]}

NAME = r"([A-Z][A-Z0-9_]*[A-Z0-9])"
NOT_WRITE = r"(?!\s*=[^=])"
PY_READS = [re.compile(p) for p in (
    rf"os\.environ\.get\(\s*[\"']{NAME}[\"']",
    rf"os\.getenv\(\s*[\"']{NAME}[\"']",
    rf"os\.environ\[\s*[\"']{NAME}[\"']\s*\]{NOT_WRITE}",
    rf"(?<![\w.])env\.get\(\s*[\"']{NAME}[\"']",
)]
JS_READS = [re.compile(p) for p in (
    rf"process\.env(?:\?\.|\.){NAME}\b{NOT_WRITE}",
    rf"process\.env\[\s*[\"']{NAME}[\"']\s*\]{NOT_WRITE}",
    rf"import\.meta\.env(?:\?\.|\.){NAME}\b",
    rf"(?<![\w.])env\.{NAME}\b{NOT_WRITE}",
)]
GROUPS = [
    ("api", "The API and its services", ("webapp/", "services/"),
     "Read by the API process (`webapp/serve.py`) and the services beside it at start-up."),
    ("web", "The website build", ("frontend/",),
     "Read by the Astro build of the website. `PUBLIC_` variables are compiled into the pages, so "
     "they are switches and public addresses, never secrets."),
    ("wiki", "The wiki build", ("docs-site/",),
     "Read by the wiki's build and its review scripts."),
    ("tools", "Tools, CI and release scripts", ("tools/", "scripts/"),
     "Read by the generators, gates and deploy scripts, locally and in GitHub Actions."),
]


def scan(root: Path = ROOT, indirect: dict[str, list[str]] = INDIRECT) -> dict[str, set[str]]:
    """name -> the files (repo-relative) that read it."""
    found: dict[str, set[str]] = {}
    for base, suffixes, pattern in SCAN:
        d = root / base
        if not d.exists():
            continue
        files = d.glob(pattern) if pattern else d.rglob("*")
        for f in files:
            rel = f.relative_to(root)
            if not f.is_file() or f.suffix not in suffixes or SKIP_FILE.match(f.name):
                continue
            if any(part in SKIP_DIRS for part in rel.parts[:-1]):
                continue
            text = f.read_text(encoding="utf-8", errors="replace")
            for rx in (PY_READS if f.suffix in PY else JS_READS):
                for m in rx.finditer(text):
                    found.setdefault(m.group(1), set()).add(rel.as_posix())
    for name, files in indirect.items():
        for rel in files:
            p = root / rel
            if not (p.exists() and re.search(rf"[\"']{name}[\"']", p.read_text(encoding="utf-8"))):
                raise SystemExit(f"gen_env_vars: INDIRECT says {rel} reads {name}, but it no longer names it — update INDIRECT")
            found.setdefault(name, set()).add(rel)
    for name in IGNORED:
        found.pop(name, None)
    return found


def group_of(files: set[str]) -> str:
    for key, _title, prefixes, _intro in GROUPS:
        if any(f.startswith(prefixes) for f in files):
            return key
    return GROUPS[-1][0]


def render(found: dict[str, set[str]], described: dict[str, str]) -> tuple[str, list[str]]:
    """The page, and the problems (an undescribed variable, a description nothing reads)."""
    problems = [f"{n} is read by {', '.join(sorted(found[n]))} but has no description in "
                f"{DESCRIPTIONS.relative_to(ROOT)}" for n in sorted(set(found) - set(described))]
    problems += [f"{n} is described in {DESCRIPTIONS.relative_to(ROOT)} but no code reads it — remove it"
                 for n in sorted(set(described) - set(found))]
    out = [
        "---",
        'title: "Environment variables"',
        'description: "Every environment variable the API, the website, the wiki and the tools read — who reads it and what it changes — generated from the code that reads it."',
        "sidebar:",
        "  order: 6",
        "---",
        HEADER,
        "# Environment variables",
        "",
        f"{len(found)} variables, found by scanning the code for the places that read them. Each row names the",
        "files that read the variable and what it changes; the descriptions are kept beside this page in",
        "`docs/reference/environment.descriptions.json`. Names only: where a variable holds a token or a secret,",
        "its value lives in the GitHub environment or the hosting project, never in the repository",
        "([environments](../process/environments.md)). Variables the CI runner sets for itself (`CI`,",
        "`GITHUB_OUTPUT`, `GITHUB_REPOSITORY`) are not listed.",
        "",
    ]
    by_group: dict[str, list[str]] = {}
    for n in sorted(found):
        by_group.setdefault(group_of(found[n]), []).append(n)
    for key, title, _prefixes, intro in GROUPS:
        names = by_group.get(key)
        if not names:
            continue
        out += [f"## {title}", "", intro, "", "| Variable | Read by | What it changes |", "|---|---|---|"]
        for n in names:
            files = ", ".join(f"`{f}`" for f in sorted(found[n]))
            out.append(f"| `{n}` | {files} | {described.get(n, '**undescribed**')} |")
        out.append("")
    out += [
        "## How this page stays true",
        "",
        "`tools/gen_env_vars.py --check` runs in the docs job and in `make docs-check`: a new read of a variable",
        "without a description, a description for a variable nothing reads any more, or a page that differs",
        "from the code fails it. To add a variable, read it in the code, add one sentence to the descriptions",
        "file and run `python3 tools/gen_env_vars.py`.",
        "",
    ]
    return "\n".join(out), problems


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    described = json.loads(DESCRIPTIONS.read_text(encoding="utf-8")) if DESCRIPTIONS.exists() else {}
    page, problems = render(scan(), described)
    for p in problems:
        print(f"::error file={DESCRIPTIONS.relative_to(ROOT)}::{p}")
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != page:
            print(f"::error file={OUT.relative_to(ROOT)}::stale — run: python3 tools/gen_env_vars.py")
            return 1
        if problems:
            return 1
        print(f"gen_env_vars: {OUT.relative_to(ROOT)} is current")
        return 0
    if problems:
        return 1
    OUT.write_text(page, encoding="utf-8")
    print(f"gen_env_vars: wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
