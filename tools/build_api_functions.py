#!/usr/bin/env python3
"""Generate the API's Vercel functions into the web project, and prove what `vercel build` bundled.

    python3 tools/build_api_functions.py --commit SHA [--db db/sggs.sqlite] [--into frontend]
    python3 tools/build_api_functions.py --add-shells .vercel/output
    python3 tools/build_api_functions.py --verify-output .vercel/output

Generate (before `vercel build`), under the web project's root:

    api/svc/<ctx>.py    one function per bounded context: fixes SGGS_MODULES, SGGS_DB and SGGS_COMMIT,
                        refuses to load if its slice lacks a declared table, and serves with serve.H
    api/svc/all.py      the whole API on the full database (every path no context function owns);
                        it also renders the Hukamnama pages, and is told the Hukamnama API's origin
                        for the environment it runs in (gateway/routes.json "hukamnama_api")
    _sggs/db/<ctx>.sqlite   the context's slice, cut and proven by tools/slice_db.py
    _sggs/db/all.sqlite     the pinned full database, unchanged
    _sggs/webapp/       serve.py and its modules (no tests, no static site)
    .python-version     3.12, the runtime the API image used
    pyproject.toml      the functions' own project: no dependencies (the API is stdlib only); without
                        it the Python builder would pick up the repository's tool-only pyproject.toml
    vercel.json         gains "functions" (per-function bundles) and "regions"; the committed file
                        has the rewrites only, so a build without these files still succeeds

Nothing here is committed (frontend/.gitignore); the routing is in frontend/vercel.json, generated
by tools/gen_gateway.py. Each function sees the original request
path and query, so serve.py routes exactly as it does on any host.

Add shells (after `vercel build`): the site build inside `vercel build` writes one Hukamnama page
shell per language to webapp/hukamnama_shells/ (frontend/scripts/extract-hukamnama-shells.mjs).
They exist only once that build has run, so they are added to the built `all` function here: copied
next to the API code it bundles and named in the function's file map. No other function gets them.

Verify (after that, before deploying): every function bundles its entry, the API code and its own
database and nothing else from the web project; `all` bundles a whole shell for every language,
and every script and stylesheet a shell names is in the static output; and no database, API source
or shell is in the static output (which the whole internet can download). Stdlib only.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from gen_gateway import (DATA_DIR, FN_DIR, REGION, ROUTES_FILE, SHELL_DIR, function_names,  # noqa: E402  one source
                         functions, hukamnama_apis, languages, shell_files)

PYTHON_VERSION = "3.12"
PYPROJECT = f'''# Generated by tools/build_api_functions.py: the API's Vercel functions (stdlib only).
[project]
name = "sggs-api-functions"
version = "0"
requires-python = ">={PYTHON_VERSION}"
dependencies = []
'''
# Files the Python builder adds to every bundle on its own.
BUILDER_FILES = (".python-version", "pyproject.toml", "uv.lock")

ENTRY = '''"""{what} (generated by tools/build_api_functions.py; do not edit)."""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
{modules}os.environ["SGGS_DB"] = os.path.join(ROOT, "{data}", "db", "{name}.sqlite")
os.environ["SGGS_COMMIT"] = "{commit}"
{pages}sys.path.insert(0, os.path.join(ROOT, "{data}", "webapp"))

import serve  # noqa: E402

# Fail closed: a function whose database lacks a table its contexts declare must not serve.
_ready = serve.readiness()
if not _ready["ready"]:
    raise RuntimeError(f"{name}: database lacks declared tables {{_ready['missing_tables']}}")


class handler(serve.H):   # Vercel finds a function by a top-level `class handler` definition
    pass
'''


# Only `all` renders the Hukamnama pages. Which API it reads depends on where it runs, so the origin
# is chosen at load time by Vercel's own VERCEL_ENV; a HUKAMNAMA_API set on the project wins (set it
# to an empty value to turn the pages off without a deploy).
PAGES = '''_hukamnama_api = {apis!r}.get(os.environ.get("VERCEL_ENV", ""))
if _hukamnama_api:
    os.environ.setdefault("HUKAMNAMA_API", _hukamnama_api)
'''


def entry(name: str, commit: str, apis: dict[str, str] | None = None) -> str:
    pages = ""
    if name == "all":
        what, modules = "The whole SGGS API on the full database", 'os.environ.pop("SGGS_MODULES", None)\n'
        pages = PAGES.format(apis=dict(sorted(apis.items()))) if apis else ""
    else:
        what, modules = f"The {name} service of the SGGS API", f'os.environ["SGGS_MODULES"] = "{name}"\n'
    return ENTRY.format(what=what, modules=modules, name=name, commit=commit, data=DATA_DIR, pages=pages)


def generate(commit: str, into: Path, db: Path) -> None:
    if len(commit) != 40 or any(c not in "0123456789abcdef" for c in commit):
        raise SystemExit("--commit must be the full 40-character source commit")
    with open(db, "rb") as f:
        if f.read(16) != b"SQLite format 3\x00":
            raise SystemExit(f"{db} is not a SQLite database (run `make dataset`)")
    fn_dir, data = into / FN_DIR, into / DATA_DIR
    for d in (fn_dir, data):
        if d.exists():
            shutil.rmtree(d)
    fn_dir.mkdir(parents=True)
    (data / "db").mkdir(parents=True)
    # hukamnama_shells: a previous local build's shells are never bundled; --add-shells adds this build's
    shutil.copytree(ROOT / "webapp", data / "webapp",
                    ignore=shutil.ignore_patterns("tests", "static", "static.bak", "_cmp", "__pycache__",
                                                  "Dockerfile", "*.md", "hukamnama_shells"))
    names = function_names()
    apis = hukamnama_apis(json.loads(ROUTES_FILE.read_text(encoding="utf-8")))
    for name in names:
        out = data / "db" / f"{name}.sqlite"
        if name == "all":
            shutil.copyfile(db, out)
        else:   # the slicer proves every kept table equal to the full DB and every FTS index whole
            subprocess.run([sys.executable, str(ROOT / "tools" / "slice_db.py"), "--db", str(db),
                            "--modules", name, "--out", str(out)], check=True)
        os.chmod(out, 0o444)
        (fn_dir / f"{name}.py").write_text(entry(name, commit, apis), encoding="utf-8")
    (into / ".python-version").write_text(PYTHON_VERSION + "\n", encoding="utf-8")
    (into / "pyproject.toml").write_text(PYPROJECT, encoding="utf-8")
    cfg = into / "vercel.json"
    doc = json.loads(cfg.read_text(encoding="utf-8")) if cfg.exists() else {}
    doc["regions"], doc["functions"] = [REGION], functions()
    cfg.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    sizes = ", ".join(f"{n} {(data / 'db' / f'{n}.sqlite').stat().st_size / 1e6:.1f} MB" for n in names)
    print(f"{len(names)} API functions at {commit[:12]} in {into} ({sizes})")


SHELL_MARKS = ('<script type="application/json" id="hk-strings">', "__HK_TITLE__", "</html>")
ASSET_RE = re.compile(r'''(?:src|href)=["\'](/_astro/[^"\'?#]+)''')


def shell_problem(text: str) -> str | None:
    """Why a file is not a whole Hukamnama page shell, or None."""
    missing = [m for m in SHELL_MARKS if m not in text]
    return f"lacks {missing}" if missing else None


def add_shells(output: Path, src: Path) -> list[str]:
    """Put this build's Hukamnama page shells into the built `all` function. Returns the bundle
    paths added. The copies sit next to the API code the function already bundles, so the deploy
    uploads them the same way (through the function's file map)."""
    cfg_path = output / "functions" / FN_DIR / "all.func" / ".vc-config.json"
    cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
    files = cfg.get("filePathMap") or {}
    anchor = f"{DATA_DIR}/webapp/serve.py"
    if not files.get(anchor, "").endswith(anchor):
        raise SystemExit(f"all: the build output does not bundle {anchor}; cannot place the shells")
    base = files[anchor][:-len(anchor)]                 # "frontend/": where the project sits in the repository
    project = output.resolve().parents[1]               # the directory `vercel build` ran in
    added = []
    for lang, rel in zip(languages(), shell_files()):
        shell = src / f"{lang}.html"
        if not shell.is_file():
            raise SystemExit(f"no Hukamnama page shell for '{lang}' at {shell}: the site build did not produce it")
        problem = shell_problem(shell.read_text(encoding="utf-8"))
        if problem:
            raise SystemExit(f"{shell} is not a whole page shell: {problem}")
        dest = project / base / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(shell, dest)
        files[rel] = base + rel
        added.append(rel)
    cfg["filePathMap"] = files
    cfg_path.write_text(json.dumps(cfg), encoding="utf-8")
    return added


def verify_output(output: Path) -> list[str]:
    """Problems with a `vercel build` output: stray files in a bundle, a missing or broken
    Hukamnama page shell, or API data in static."""
    problems = []
    names = function_names()
    shells, project, static = shell_files(), output.resolve().parents[1], output / "static"
    for name in names:
        cfg = output / "functions" / FN_DIR / f"{name}.func" / ".vc-config.json"
        if not cfg.is_file():
            problems.append(f"{name}: no function in the build output ({cfg})")
            continue
        path_map = json.loads(cfg.read_text(encoding="utf-8")).get("filePathMap", {})
        files = set(path_map)
        own = f"{DATA_DIR}/db/{name}.sqlite"
        if own not in files:
            problems.append(f"{name}: its database {own} is not bundled")
        for rel in shells:
            if name != "all":
                if rel in files:
                    problems.append(f"{name}: bundles the Hukamnama page shell {rel}; only `all` renders pages")
                continue
            source = project / path_map.get(rel, "")
            if rel not in files or not source.is_file():
                problems.append(f"all: the Hukamnama page shell {rel} is not bundled (run --add-shells after the build)")
                continue
            text = source.read_text(encoding="utf-8")
            problem = shell_problem(text)
            if problem:
                problems.append(f"all: {rel} is not a whole page shell: {problem}")
            for asset in sorted(set(ASSET_RE.findall(text))):
                if not (static / asset.lstrip("/")).is_file():
                    problems.append(f"all: {rel} names {asset}, which is not in the static output")
        for f in sorted(files):
            if f == own or f.startswith((f"{DATA_DIR}/webapp/", f"{FN_DIR}/", "_vendor/")) or f in BUILDER_FILES:
                continue
            problems.append(f"{name}: bundles {f}, which is not part of the API")
    if static.is_dir():
        for p in static.rglob("*"):
            rel = p.relative_to(static).as_posix()
            if p.is_file() and (rel.startswith((f"{DATA_DIR}/", f"{FN_DIR}/")) or rel.endswith((".sqlite", ".py"))):
                problems.append(f"static output would publish {rel}")
            # The Hukamnama page shell is a template full of tokens, never a page. The site build
            # (frontend/scripts/extract-hukamnama-shells.mjs) removes it from the output; if a build
            # skipped that step, refuse to deploy rather than publish it.
            if p.is_file() and "/hukamnama/hk-shell" in "/" + rel:
                problems.append(f"static output would publish the Hukamnama page shell: {rel}")
    return problems


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--commit")
    ap.add_argument("--into", type=Path, default=ROOT / "frontend")
    ap.add_argument("--db", type=Path, default=ROOT / "db" / "sggs.sqlite")
    ap.add_argument("--verify-output", type=Path, metavar="DIR")
    ap.add_argument("--add-shells", type=Path, metavar="DIR",
                    help="add this build's Hukamnama page shells to the built `all` function")
    ap.add_argument("--shells", type=Path, default=ROOT / SHELL_DIR)
    a = ap.parse_args(argv)
    if a.add_shells:
        added = add_shells(a.add_shells, a.shells)
        print(f"added {len(added)} Hukamnama page shell(s) to the `all` function: {', '.join(added)}")
        return 0
    if a.verify_output:
        problems = verify_output(a.verify_output)
        for p in problems:
            print(f"::error::{p}")
        print(f"{'FAIL' if problems else 'OK'}: {len(function_names())} API functions in {a.verify_output}")
        return 1 if problems else 0
    generate(a.commit or "", a.into, a.db)
    return 0


if __name__ == "__main__":
    sys.exit(main())
