#!/usr/bin/env python3
"""Generate the contributors pages from frontend/public/contributors.json (roster schema v2).

    python3 tools/gen_contributors.py            # rewrite both pages
    python3 tools/gen_contributors.py --check    # exit 1 if a committed page differs (CI)

Two pages, one source:
- docs/reference/contributors.md — the wiki's chronology of the voices of the Granth;
- docs/review/lineage-roster-v2.md — the G3 review pack: every roster field with the source it rests on,
  the verse that proves each pen-name, and the questions only a scholar can settle.

Names are the corpus `author` strings, so the API's author counts join them. Life facts come only from the
sources each entry cites (tools/check_contributors.py enforces it); an unknown date stays blank. Historical
context only, never a ranking. Stdlib only.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "frontend" / "public" / "contributors.json"
OUT = ROOT / "docs" / "reference" / "contributors.md"
REVIEW_OUT = ROOT / "docs" / "review" / "lineage-roster-v2.md"
HEADER = "<!-- generated by tools/gen_contributors.py from frontend/public/contributors.json — do not edit; run the generator -->"
KIND = {"guru": "The Gurus", "bhagat": "The Bhagats", "bhatt": "The Bhatts", "gursikh": "Gursikhs"}
GM_RUN = re.compile(r"[਀-੿][਀-੿‌‍ ]*[਀-੿]|[਀-੿]")
CORPUS_FIELDS = {"chhap", "chhap_example", "notable", "attribution_note"}


def load() -> dict:
    return json.loads(SRC.read_text(encoding="utf-8"))


def gm(text: str | None) -> str:
    """Prose-safe text: a Gurmukhi run of four words or more (or 30+ characters) is a quotation, so it goes
    in a code span — the wiki's scripture rule keeps uncited verse out of prose (tools/docs_check.py)."""
    if not text:
        return "—"

    def wrap(m: re.Match) -> str:
        run = m.group(0)
        return f"`{run}`" if len(run.split()) >= 4 or len(run) >= 30 else run
    return GM_RUN.sub(wrap, text.replace('"', "")).replace("|", "\\|")


def lived(r: dict) -> str:
    b, d, c = r.get("born"), r.get("died"), "c. " if r.get("circa") else ""
    if b and d:
        return f"{c}{b}–{d}"
    if b:
        return f"b. {c}{b}"
    if d:
        return f"d. {c}{d}"
    return f"fl. {r['fl_century']}th c." if r.get("fl_century") else "not recorded"


def grouped(rows: list[dict]):
    for kind, label in KIND.items():
        group = [r for r in rows if r.get("kind") == kind]
        if group:
            group.sort(key=lambda r: ((r.get("seq") or 0), (r.get("born") or r.get("died") or (r.get("fl_century") or 99) * 100 - 50), r["name"]))
            yield kind, label, group


def build() -> str:
    d = load()
    rows = d["contributors"]
    lines = [
        "---",
        'title: "The contributors to the Granth"',
        'description: "Who wrote the hymns of Sri Guru Granth Sahib Ji: the Gurus, the Bhagats, the Bhatts and the Gursikhs, with their dates, places and sources — the roster the site and the app show."',
        "sidebar:",
        "  order: 4",
        "---",
        HEADER,
        "# The contributors to the Granth",
        "",
        f"The roster names {len(rows)} voices. Each *name in the corpus* is the `author` string of the database, so",
        "`/api/analytics/author` and the [structure page](../scripture/structure.md) join to it, and the",
        "[Ang explorer](../data/line-record.md) shows their lines. A voice the attribution repair in sggs-data is",
        "still adding has no lines in the corpus yet. Dates come only from the sources each entry cites; an",
        "unknown date is left blank (*c.* marks an uncertain one, *fl.* the century a voice is known from). Every",
        "entry is a draft until the scholar signs the [review pack](../review/lineage-roster-v2.md) (gate G3).",
        "This is historical context, never a ranking.",
        "",
    ]
    for _kind, label, group in grouped(rows):
        lines += [f"## {label} ({len(group)})", "", "| Name in the corpus | Name | Lived | Era | Region | Tradition |", "|---|---|---|---|---|---|"]
        for r in group:
            lines.append(f"| {r['name']} | {r.get('display') or r.get('roman')} | {lived(r)} | {r.get('era') or '—'} | {r.get('region') or '—'} | {r.get('tradition') or '—'} |")
        lines.append("")
        for r in group:
            if r.get("context") or r.get("blurb"):
                lines.append(f"- **{r.get('display') or r['name']}** — {gm(r.get('context') or r.get('blurb'))}")
        lines.append("")
    lines += ["Source: `frontend/public/contributors.json` (vendored by the app at each platform release). To change an",
              "entry, edit the JSON, run `python3 tools/check_contributors.py`, then `python3 tools/gen_contributors.py`.", ""]
    return "\n".join(lines)


def cite(r: dict, field: str, index: dict) -> str:
    refs = []
    for s in r.get("sources") or []:
        if field in (s.get("supports") or []):
            label = f"{s['ref']}: {s['entry']}"
            refs.append(f"[{label}]({s['url']})" if s.get("url") else label)
    if not refs and field in CORPUS_FIELDS | {"name", "gurmukhi", "display", "kind", "era", "region", "tradition", "blurb", "circa"}:
        return "corpus" if field in CORPUS_FIELDS | {"name"} else "editorial (to review)"
    return "; ".join(gm(x) for x in refs) or "—"


def review_entry(r: dict, index: dict) -> list[str]:
    out = [f"### {r.get('display') or r['name']}", ""]
    rows = [
        ("Name in the corpus", f"`{r['name']}`", cite(r, "name", index)),
        ("Display name", r.get("display"), cite(r, "display", index)),
        ("Gurmukhi", gm(r.get("gurmukhi")), cite(r, "gurmukhi", index)),
        ("Lived", lived(r), cite(r, "born", index) if r.get("born") else cite(r, "died", index) if r.get("died") else cite(r, "fl_century", index)),
        ("Dates note", gm(r.get("range_note")), cite(r, "range_note", index) if r.get("range_note") else "—"),
        ("Birthplace", gm(r.get("birthplace")), cite(r, "birthplace", index) if r.get("birthplace") else "—"),
    ]
    p = r.get("place")
    rows.append(("Map pin", f"{p['label']} ({p['lat']}, {p['lon']}; approximate)" if p else "none", cite(r, "place", index) if p else "—"))
    rows.append(("Pen-name (chhap)", ", ".join(r.get("chhap") or []) or "none", "corpus (whole-word match; the verse below)" if r.get("chhap") else "—"))
    for n in r.get("notable") or []:
        rows.append(("Notable Bani", f"{n['title']} ({gm(n.get('gurmukhi'))}) — comp {n['comp_id']}, Ang {n['ang']}", f"corpus (anchor `{n['anchor']}`)"))
    out += ["| Field | Value | Source |", "|---|---|---|"] + [f"| {a} | {b if b else '—'} | {c} |" for a, b, c in rows] + [""]
    out += [f"**Context.** {gm(r.get('context'))}", "", f"*Sources:* {cite(r, 'context', index)}", ""]
    if r.get("disputed"):
        out += [f"**Where sources differ.** {gm(r['disputed'])} *({cite(r, 'disputed', index)})*", ""]
    if r.get("attribution_note"):
        out += [f"**In the corpus today.** {gm(r['attribution_note'])}", ""]
    for note in (r.get("review") or {}).get("notes") or []:
        out += [f"**For the scholar.** {gm(note)}", ""]
    ex = r.get("chhap_example")
    if ex and r.get("_example_text"):
        out += ["The pen-name in a verse:", "", f"> {r['_example_text']}", ">", f"> — Sri Guru Granth Sahib Ji · Ang {ex['ang']}", ""]
    status = (r.get("review") or {}).get("status", "draft")
    out += [f"Review: **{status}** · reviewer: ________ · date: ________", ""]
    return out


SIDECAR = REVIEW_OUT.with_suffix(".verses.json")


def example_texts() -> dict[int, str]:
    """The verbatim verses the pen-name examples point at, pinned in a sidecar so the page builds (and --check
    runs) without the database. Write mode refreshes it from db/sggs.sqlite; check_contributors.py and
    docs_check.py --db prove each one is a verbatim line of its Ang."""
    if not SIDECAR.exists():
        return {}
    return {int(k): v for k, v in json.loads(SIDECAR.read_text(encoding="utf-8")).items()}


def refresh_sidecar(rows: list[dict]) -> list[int]:
    """Re-read the example verses from the pinned DB; returns the line ids it could not find."""
    import sqlite3
    ids = sorted({r["chhap_example"]["line_id"] for r in rows if r.get("chhap_example")})
    db = ROOT / "db" / "sggs.sqlite"
    if not db.exists():
        return sorted(set(ids) - set(example_texts()))
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    found = dict(con.execute(f"SELECT id, gurmukhi FROM lines WHERE id IN ({','.join('?' * len(ids))})", ids))
    SIDECAR.parent.mkdir(parents=True, exist_ok=True)
    SIDECAR.write_text(json.dumps({str(k): found[k] for k in sorted(found)}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return sorted(set(ids) - set(found))


def build_review(texts: dict[int, str] | None = None) -> str:
    d = load()
    rows = [dict(r) for r in d["contributors"]]
    index = d.get("source_index") or {}
    texts = example_texts() if texts is None else texts
    for r in rows:
        if r.get("chhap_example"):
            r["_example_text"] = texts.get(r["chhap_example"]["line_id"])
    statuses = {}
    for r in rows:
        s = (r.get("review") or {}).get("status", "draft")
        statuses[s] = statuses.get(s, 0) + 1
    lines = [
        "---",
        'title: "Lineage roster v2: the review pack"',
        'description: "Every field of the 36-voice contributors roster with the source it rests on, the verse that proves each pen-name, and the questions for the scholar (gate G3)."',
        "sidebar:",
        "  order: 1",
        "---",
        HEADER,
        "# Lineage roster v2: the review pack",
        "",
        f"This pack is for the scholar who signs gate G3. It sets out the {len(rows)}-voice roster that the website's",
        "Lineage page and the app's *Voices of the Granth* read (`frontend/public/contributors.json`), field by",
        "field, with the source behind each one. It is presentation data: it never alters the scripture, and every",
        "count and Ang on screen comes from the database, not from here. Status today: "
        + ", ".join(f"{n} {s}" for s, n in sorted(statuses.items())) + ".",
        "",
        "## How the facts were chosen",
        "",
        "1. **The Granth itself first.** Pen-names (*chhap*), the verse that shows each one, and the named Banis",
        "   (by `comp_id`) are read from this project's verbatim corpus; `tools/check_contributors.py` re-proves",
        "   them against the pinned database on every pull request.",
        "2. **Life facts only from tier-2 sources**, named on every row:",
    ]
    for key, s in index.items():
        lines.append(f"   - **{key}** — {s['title']}" + (f" ({s['url']})" if s.get("url") else "") + (f". {s['note']}" if s.get("note") else ""))
    lines += [
        "3. **Wikipedia, SikhiWiki and the ShabadOS writer field are for discovery only** and are never cited.",
        "4. **Never invent a date or a place.** A field no source supports is left blank, and its *Dates note*",
        "   says why. *c.* marks an uncertain date; *fl.* gives the century a voice is known from, and is used",
        "   only to order the timeline.",
        "5. **Where sources differ, the entry says so**, in the *Where sources differ* line.",
        "",
        "Map pins are approximate. They sit on an equirectangular box over north and west India",
        f"(longitude {d['map']['lon'][0]}–{d['map']['lon'][1]}°E, latitude {d['map']['lat'][0]}–{d['map']['lat'][1]}°N),",
        "and each one names a town that a source ties to the voice.",
        "",
        "## How to sign",
        "",
        "For each voice, correct anything wrong (in the JSON or on this page), then set its `review` to",
        '`{"status": "approved", "reviewer": "<name>", "date": "YYYY-MM-DD"}`. The App Store build runs',
        "`python3 tools/check_contributors.py --channel appstore`, which refuses any entry that is not approved.",
        "TestFlight shows a *Context pending scholarly review* label in the meantime.",
        "",
        "## Questions for the scholar",
        "",
        "- **How many Bhatts?** Sahib Singh and Teja Singh count 11; Santokh Singh and Bhai Vir Singh count 17;",
        "  Kartar Singh Dakha counts 19 (EoS, Bhatt Bani). The roster follows the corpus's 11 names plus a",
        "  collective entry for unattributed Swaiyye lines. Should the 17-count names (Tal, Jalan, Das, Sevak,",
        "  Parmanand the Bhatt) be shown, and under which of the 11? Kalsahar's verses also sign `ਟਲ`, which the",
        "  17-count treats as Bhatt Tal.",
        "- **Bhai Mardana.** The EoS credits him with one salok at Ang 553. Sahib Singh (Darpan, Ang 553) reads all",
        "  three saloks headed `ਮਰਦਾਨਾ ੧` as Guru Nanak's, addressed to Mardana. Keep him as a voice, or show the",
        "  saloks under Guru Nanak?",
        "- **Bhagat Surdas.** One line, with no pen-name. The roster follows the EoS and Sahib Singh: the shabad",
        "  headed `ਸਾਰੰਗ ਮਹਲਾ ੫ ਸੂਰਦਾਸ` is Guru Arjan's. Confirm.",
        "- **Raagmala** (Angs 1429–1430) has no author in the printed caption, and its authorship is contested",
        "  (EoS, Ragmala). The corpus files it under Guru Arjan Dev Ji, and no roster entry claims it.",
        "- **Japji Sahib** has no `author` in today's corpus (Angs 1–8). It is listed as Guru Nanak's notable Bani;",
        "  the attribution repair in sggs-data assigns it.",
        "- **Gurmukhi forms of the names** (`gurmukhi`) are editorial, in modern spelling (e.g. `ਭੱਟ ਕਲਸਹਾਰ ਜੀ`).",
        "  Approve or correct each one.",
        "",
    ]
    for _kind, label, group in grouped(rows):
        lines += [f"## {label} ({len(group)})", ""]
        for r in group:
            lines += review_entry(r, index)
    lines += ["Source: `frontend/public/contributors.json`. Regenerate with `python3 tools/gen_contributors.py`; the",
              "example verses are pinned in `docs/review/lineage-roster-v2.verses.json` so the page builds without the database.", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    pages = {OUT: build(), REVIEW_OUT: build_review()}
    if "--check" in argv:
        stale = [p for p, text in pages.items() if (p.read_text(encoding="utf-8") if p.exists() else "") != text]
        for p in stale:
            print(f"::error file={p.relative_to(ROOT)}::stale — run: python3 tools/gen_contributors.py")
        if stale:
            return 1
        print("gen_contributors: " + ", ".join(str(p.relative_to(ROOT)) for p in pages) + " are current")
        return 0
    missing = refresh_sidecar(load()["contributors"])
    if missing:
        print(f"::error::example verses {missing} are not in the database — run `make dataset` first")
        return 1
    for p, text in {OUT: build(), REVIEW_OUT: build_review()}.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
